    # 2. 정확도 검증
    print("\n[2/3] 양자화 정확도 검증...")
    validate_tflite(TFLITE_PATH)

    # 3. C 헤더 생성
    print("\n[3/3] C 헤더 파일 생성...")
    generate_c_header(TFLITE_PATH, C_HEADER)

    print("\n" + "=" * 60)
    print("완료!")
    print(f"TFLite 모델:  {TFLITE_PATH}")
    print(f"C 헤더:       {C_HEADER}")
